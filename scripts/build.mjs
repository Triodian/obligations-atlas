// Copy the shared core into public/ so the browser can import it as /core/atlas.js, and turn the vendored Metamodel's
// regulated domains (reference-data/regulated-domains.json) into src/core/domains.js, which the core imports.
import fs from 'node:fs';
const ref = JSON.parse(fs.readFileSync('vendor/triodian-metamodel/reference-data/regulated-domains.json', 'utf8'));
const js = `// Generated by scripts/build.mjs from vendor/triodian-metamodel/reference-data/regulated-domains.json. Do not edit.
export const REGULATED_DOMAINS = ${JSON.stringify(ref.items, null, 2)};
`;
if (!fs.existsSync('src/core/domains.js') || fs.readFileSync('src/core/domains.js', 'utf8') !== js) fs.writeFileSync('src/core/domains.js', js);
fs.mkdirSync('public/core', { recursive: true });
fs.copyFileSync('src/core/atlas.js', 'public/core/atlas.js');
fs.copyFileSync('src/core/domains.js', 'public/core/domains.js');
console.log('public/core/atlas.js and domains.js updated');
